def add_panel_label(ax, label, x=-0.16, y=1.04, fontsize=13, fontweight='bold'):
    """Place a Nature-style panel label at the top-left edge."""
    ax.text(
        x, y, label,
        transform=ax.transAxes,
        fontsize=fontsize,
        fontweight=fontweight,
        ha='left',
        va='bottom',
        color='#000000'
    )


def load_processed_data():
    datasets = {}
    for c in COUNTRIES:
        path = os.path.join(PROCESSED_DIR, f'{c}_features.parquet')
        if os.path.exists(path):
            datasets[c] = pd.read_parquet(path)
    return datasets


